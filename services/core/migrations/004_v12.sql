CREATE TABLE IF NOT EXISTS driver_docs (tenant_id text NOT NULL REFERENCES tenants(id), id text NOT NULL, data jsonb NOT NULL, updated_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY (tenant_id, id));
ALTER TABLE driver_docs ENABLE ROW LEVEL SECURITY;
ALTER TABLE driver_docs FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON driver_docs;
CREATE POLICY tenant_isolation ON driver_docs USING (tenant_id = current_setting('app.tenant', true)) WITH CHECK (tenant_id = current_setting('app.tenant', true));
GRANT SELECT, INSERT, UPDATE, DELETE ON driver_docs TO app_user;
